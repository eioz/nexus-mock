static std::string get_mock_encounter_name(TriggerID trigger_id, const std::filesystem::path& evtc_file_path)
{
	if (auto it = EncounterNames.find(trigger_id); it != EncounterNames.end())
		return it->second;

	auto stem = evtc_file_path.stem().string();
	return stem.empty() ? "Mock Encounter" : stem;
}

static std::string sanitize_mock_id(std::string id)
{
	for (auto& c : id)
		if (!std::isalnum(static_cast<unsigned char>(c)))
			c = '_';
	return id.empty() ? "mock_log" : id;
}

static ParserData create_mock_parser_data(const Log& log)
{
	ParserData data;
	data.status = ParseStatus::PARSED;

	auto end_time = log.evtc_file_time;
	if (end_time.time_since_epoch().count() == 0)
		end_time = std::chrono::system_clock::now();

	data.encounter.name = get_mock_encounter_name(log.trigger_id, log.evtc_file_path);
	data.encounter.account_name = "MockAccount.0000";
	data.encounter.duration_ms = 92345;
	data.encounter.success = true;
	data.encounter.has_boss = true;
	data.encounter.health_percent_burned = 100.f;
	data.encounter.difficulty = EncounterDifficulty::NORMAL_MODE;
	data.encounter.end_time = end_time;
	data.encounter.start_time = end_time - std::chrono::milliseconds(data.encounter.duration_ms);

	auto output_directory = addon::directory / "mock-reports";
	std::filesystem::create_directories(output_directory);

	auto safe_id = sanitize_mock_id(log.id);
	data.html_file_path = output_directory / (safe_id + ".html");
	data.json_file_path = output_directory / (safe_id + ".json");

	{
		std::ofstream html(data.html_file_path);
		html << "<!doctype html><title>Mock report</title><h1>" << data.encounter.name << "</h1><p>Generated by the macOS native mock.</p>";
	}

	{
		std::ofstream json(data.json_file_path);
		json << "{\n"
		     << "  \"mock\": true,\n"
		     << "  \"encounter\": \"" << data.encounter.name << "\",\n"
		     << "  \"account\": \"" << data.encounter.account_name << "\"\n"
		     << "}\n";
	}

	return data;
}

void Parser::initialize()
{
	loaded.store(true);

	parser_thread = std::thread(&Parser::run, this);
}

void Parser::release()
{
	loaded.store(false);

	clear_parser_queue();

	parser_cv.notify_all();

	if (parser_thread.joinable())
		parser_thread.join();
}

void Parser::add_log(std::shared_ptr<Log> log)
{
	if (!loaded.load())
		return;

	std::unique_lock lock(log->mutex);

	if (log->parser_data.status != ParseStatus::UNPARSED)
	{
		addon::log("Log unavailable for parsing: " + log->id, LOGLEVEL_WARNING);
		return;
	}

	log->parser_data.status = ParseStatus::QUEUED;

	{
		std::unique_lock parser_queue_lock(parser_queue_mutex);
		parser_queue.push(log);
		parser_cv.notify_one();
	}
}

void Parser::run()
{
	addon::log("Starting mock parser", LOGLEVEL_DEBUG);

	while (true)
	{
		std::unique_lock parser_queue_lock(parser_queue_mutex);

		parser_cv.wait(parser_queue_lock, [this] { return !loaded.load() || !parser_queue.empty(); });

		if (!loaded.load())
			break;

		auto log = parser_queue.front();
		parser_queue.pop();

		parser_queue_lock.unlock();

		std::unique_lock log_lock(log->mutex);

		log->parser_data.status = ParseStatus::PARSING;
		log->update_view();

		log_lock.unlock();

		std::this_thread::sleep_for(std::chrono::milliseconds(150));

		try
		{
			auto parser_data = create_mock_parser_data(*log);

			{
				std::unique_lock lock(log->mutex);
				log->parser_data = parser_data;
				log->update_view();
			}

			addon::dps_report_uploader->process_auto_upload(log);
			addon::wingman_uploader->process_auto_upload(log);
		}
		catch (const std::exception& e)
		{
			std::unique_lock lock(log->mutex);
			log->parser_data.status = ParseStatus::FAILED;
			log->parser_data.error_message = e.what();
			addon::log("Mock parse failed for " + log->id + ". Exception: " + e.what(), LOGLEVEL_WARNING);
			log->update_view();
		}
	}

	addon::log("Stopping mock parser", LOGLEVEL_DEBUG);
}
